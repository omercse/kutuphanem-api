-- Baslangic semasi.
-- Bu dosya daha once Hibernate'in ddl-auto=create ile urettigi semanin
-- birebir karsiligidir. Artik semayi Hibernate degil Flyway yonetiyor.

CREATE TABLE authors (
                         id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
                         name VARCHAR(255) NOT NULL UNIQUE,
                         PRIMARY KEY (id)
);

CREATE TABLE categories (
                            id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
                            name VARCHAR(255) NOT NULL UNIQUE,
                            PRIMARY KEY (id)
);

CREATE TABLE users (
                       id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
                       email      VARCHAR(255) NOT NULL UNIQUE,
                       first_name VARCHAR(255),
                       last_name  VARCHAR(255),
                       password   VARCHAR(255) NOT NULL,
                       role       VARCHAR(255) CHECK (role IN ('USER', 'ADMIN')),
                       PRIMARY KEY (id)
);

CREATE TABLE books (
                       id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
                       excel_sira_no INTEGER,
                       title         VARCHAR(255),
                       status        VARCHAR(255),
                       author_id     BIGINT NOT NULL,
                       category_id   BIGINT NOT NULL,
                       PRIMARY KEY (id),
                       CONSTRAINT fk_books_author
                           FOREIGN KEY (author_id) REFERENCES authors (id),
                       CONSTRAINT fk_books_category
                           FOREIGN KEY (category_id) REFERENCES categories (id)
);

-- Sorgu performansi icin: kitaplar surekli yazar ve kategoriye gore
-- filtreleniyor, baslik uzerinden arama yapiliyor.
CREATE INDEX idx_books_author_id   ON books (author_id);
CREATE INDEX idx_books_category_id ON books (category_id);
CREATE INDEX idx_books_status      ON books (status);